from pathlib import Path
import json


class PreprocessingSummary:
    """
    Collects preprocessing results generated by each stage
    of the preprocessing pipeline.

    Responsibilities
    ----------------
    1. Store results from every preprocessing module.
    2. Provide access to stored sections.
    3. Export report as JSON.
    4. Print a readable summary.
    """

    def __init__(self):

        self._report = {}

    def add(self, section, key, value):

        if section not in self._report:
            self._report[section] = {}

        self._report[section][key] = value 

    def get(self, section, default=None):

        return self._report.get(section, default)
 

    def to_dict(self):

        return self._report

    def has_errors(self):
        """Check if any preprocessing stage encountered errors."""
        errors = self._report.get("pipeline_errors")
        return bool(errors and len(errors) > 0)

    def get_errors(self):
        """Get dictionary of pipeline stage errors, if any."""
        return dict(self._report.get("pipeline_errors", {}))


    def save_json(self, output_path):

        output_path = Path(output_path)

        output_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        with open(output_path, "w", encoding="utf-8") as file:

            json.dump(
                self._report,
                file,
                indent=4,
                default=str,
            )
 

    def pretty_print(self):

        print("\n" + "=" * 70)
        print("PREPROCESSING SUMMARY")
        print("=" * 70)

        for section, content in self._report.items():

            print(f"\n[{section.upper()}]")

            if isinstance(content, dict):

                for key, value in content.items():

                    print(f"{key}: {value}")

            else:

                print(content)